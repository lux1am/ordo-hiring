"""Метка размещения: откуда пришёл отклик.

Ссылка на анкету раздаётся с параметром `?src=`, форма кладёт его значение
в скрытое поле, и оно уезжает в колонку `source` вместе с ответами. Метки
придумывает не человек: их выдаёт таблица формулой. Их два вида, и по виду
метки видно, откуда отклик:

    p002        — размещение в канале, номер строки листа «Размещения»
    lk_16_10    — личные касания за 16 октября, лист «Личные касания»

Ника копирует готовую ссылку и вставляет в пост или в сообщение, руками не
вписывая ничего.

Значение приходит из адресной строки, то есть от кого угодно. Поэтому оно
чистится, а не принимается как есть: в таблицу должно попадать короткое
техническое слово, а не разметка, перевод строки или чужой текст на
полэкрана. Чистка одна и та же в трёх местах — здесь, в общем JS формы и в
Code.gs, — и совпадение закреплено тестами: разойдясь, они дали бы разные
метки в зависимости от того, через какую форму пришла анкета.
"""
import re
from datetime import date

# Длина с запасом: настоящая метка — четыре знака. Предел нужен не для них,
# а чтобы в ячейку не уехала километровая строка из адреса.
SOURCE_MAX_LEN = 40

# Префикс метки размещения. Номер строки листа «Размещения» дописывается к
# нему с ведущими нулями: строка 2 -> p002.
LABEL_PREFIX = "p"
LABEL_DIGITS = 3

# Метка личных касаний: день и месяц, по строке на день. Года в ней нет
# намеренно — метка должна читаться глазами в посте и в таблице, а отчёт
# всё равно смотрит только на прошедшую неделю.
OUTREACH_PREFIX = "lk_"
OUTREACH_DATE_FORMAT = "%d_%m"

# Латиница, цифры, подчёркивание, дефис. Всё остальное выбрасывается —
# именно выбрасывается, а не заменяется: заменять нечем, метка техническая.
_DROP_RE = re.compile(r"[^a-z0-9_-]")


def clean(raw) -> str:
    """Значение `src` из адреса, приведённое к виду метки. Нет метки — пусто."""
    return _DROP_RE.sub("", str(raw if raw is not None else "").strip().lower())[
        :SOURCE_MAX_LEN
    ]


def label(row: int) -> str:
    """Метка размещения по номеру строки листа «Размещения»: 2 -> «p002»."""
    return f"{LABEL_PREFIX}{row:0{LABEL_DIGITS}d}"


def outreach_label(day: date) -> str:
    """Метка личных касаний по дате: 16 октября -> «lk_16_10»."""
    return OUTREACH_PREFIX + day.strftime(OUTREACH_DATE_FORMAT)


def is_outreach(value: str) -> bool:
    """Метка личных касаний? По ней отклики из личек считаются отдельно."""
    return str(value or "").startswith(OUTREACH_PREFIX)
